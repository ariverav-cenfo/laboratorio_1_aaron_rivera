CREATE TABLE producto(
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto varchar(100) NOT NULL,
    descrcipcion_producto varchar(250) NOT NULL,
    precio numeric(38,2) NOT NULL,
    stock INTEGER NOT NULL,
    categoria_id BIGINT NOT NULL ,
    CONSTRAINT FK_Producto_Categoria_IdCategoria FOREIGN KEY (categoria_id) REFERENCES categoria(categoria_id)
);

CREATE INDEX IX_Producto_Nombre ON producto (nombre_producto);
CREATE INDEX IX_Producto_Categoria on producto(categoria_id);



